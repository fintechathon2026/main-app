// Writes src/server/chain/abi.ts from the Foundry artifacts (PRD_PrepaidEscrow_Contract §5).
// Run after changing a contract:
//   (cd contracts && forge build) && node --no-warnings --experimental-transform-types scripts/export-contract-abi.ts
// tests/chain/abi.test.ts fails when the committed file and the artifacts disagree.
// Self-contained (no path aliases) so Node can run it directly with type stripping.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const CONTRACTS = [
  { name: "PrepaidEscrow", exportName: "PREPAID_ESCROW_ABI" },
  { name: "TestCNY", exportName: "TEST_CNY_ABI" },
];

export function renderAbiModule(read: (name: string) => unknown[]): string {
  const parts = [
    "// GENERATED by scripts/export-contract-abi.ts from contracts/out. Do not edit by hand.",
    "// Pure data: no keys, no I/O. Shared by the chain adapter, the indexer and the simulators.",
    "",
  ];
  for (const c of CONTRACTS) {
    parts.push(`export const ${c.exportName} = ${JSON.stringify(read(c.name), null, 2)} as const;`, "");
  }
  return parts.join("\n");
}

export function readArtifactAbi(name: string): unknown[] {
  const json = JSON.parse(readFileSync(`${root}contracts/out/${name}.sol/${name}.json`, "utf8")) as { abi: unknown[] };
  return json.abi;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const out = `${root}src/server/chain/abi.ts`;
  writeFileSync(out, renderAbiModule(readArtifactAbi));
  console.log(`wrote ${out}`);
}
